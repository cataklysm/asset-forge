import { describe, expect, it } from 'vitest';
import { isPublicAddress } from '../src/index.js';

describe('isPublicAddress', () => {
  it.each([
    ['0.0.0.0/8', '0.1.2.3'],
    ['10/8', '10.0.0.1'],
    ['100.64/10', '100.100.1.1'],
    ['127/8', '127.0.0.1'],
    ['169.254/16', '169.254.169.254'],
    ['172.16/12', '172.31.255.1'],
    ['192.0.0/24', '192.0.0.8'],
    ['192.0.2/24', '192.0.2.10'],
    ['192.88.99/24', '192.88.99.1'],
    ['192.168/16', '192.168.1.1'],
    ['198.18/15', '198.19.0.1'],
    ['198.51.100/24', '198.51.100.7'],
    ['203.0.113/24', '203.0.113.9'],
    ['224/4', '239.255.255.250'],
    ['240/4', '240.0.0.1'],
    ['broadcast', '255.255.255.255'],
    ['::', '::'],
    ['::1', '::1'],
    ['fc00::/7', 'fd12:3456::1'],
    ['fe80::/10', 'fe80::1'],
    ['ff00::/8', 'ff02::1'],
    ['2001:db8::/32', '2001:db8::1'],
    ['64:ff9b::/96 private', '64:ff9b::10.0.0.1'],
    ['64:ff9b::/96 loopback hex', '64:ff9b::7f00:1'],
    ['2002::/16 private', '2002:c0a8:0101::1'],
    ['2002::/16 loopback', '2002:7f00:1::'],
    ['::ffff:0:0/96 dotted loopback', '::ffff:127.0.0.1'],
    ['::ffff:0:0/96 hex loopback', '::ffff:7f00:1'],
    ['::ffff:0:0/96 private', '::ffff:10.0.0.1'],
    ['zone id', 'fe80::1%eth0'],
    ['zone id on a public address', '2606:4700:4700::1111%1'],
    ['not an address', 'not-an-ip'],
    ['empty', ''],
    ['host name', 'example.com'],
  ])('refuses %s (%s)', (_range, address) => {
    expect(isPublicAddress(address)).toBe(false);
  });

  it.each([
    '8.8.8.8',
    '1.1.1.1',
    '93.184.216.34',
    '172.32.0.1',
    '100.128.0.1',
    '2606:4700:4700::1111',
    '::ffff:8.8.8.8',
    '::ffff:808:808',
    '64:ff9b::8.8.8.8',
    '2002:808:808::1',
  ])('accepts %s', (address) => {
    expect(isPublicAddress(address)).toBe(true);
  });
});
