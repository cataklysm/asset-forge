/**
 * Whether a channel name is one of the IPC contract.
 *
 * @param channel the name the renderer passed
 * @returns true for a known channel
 */
export function isKnownChannel(channel: string): channel is IpcChannel {
  return Object.hasOwn(KNOWN_CHANNELS, channel);
}
